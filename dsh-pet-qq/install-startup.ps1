<#
install-startup.ps1 —— 把看门狗注册到当前用户的「启动」文件夹（幂等，可重复运行）。

登录时由 explorer 拉起 watchdog.ps1，进程属于桌面会话，不随任何对话任务回收。
  -Uninstall  移除启动项（不影响正在运行的看门狗）
#>
param([switch]$Uninstall)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$startup = [Environment]::GetFolderPath('Startup')
$link = Join-Path $startup 'dsh-pet-qq-watchdog.vbs'

if ($Uninstall) {
  if (Test-Path $link) {
    Remove-Item $link -Force
    Write-Host "已移除启动项：$link"
  } else {
    Write-Host '启动项本来就不存在'
  }
  exit 0
}

$ps1 = Join-Path $root 'watchdog.ps1'
$runLine = 'CreateObject("WScript.Shell").Run "powershell -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""' + $ps1 + '""", 0, False'
$content = "' dsh-pet-qq watchdog (generated by install-startup.ps1)`r`n" + $runLine + "`r`n"

$needWrite = $true
if (Test-Path $link) {
  $old = Get-Content $link -Raw
  if ($old -eq $content) {
    $needWrite = $false
  } else {
    Copy-Item $link "$link.bak-$(Get-Date -Format yyyyMMdd-HHmm)" -Force
  }
}

if ($needWrite) {
  [System.IO.File]::WriteAllText($link, $content, (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "已写入启动项：$link"
} else {
  Write-Host "启动项已是最新：$link"
}
